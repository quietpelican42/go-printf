// Generates src/isprint.ts from Go's strconv/isprint.go.
// usage: node scripts/gen-isprint.mjs "$(go env GOROOT)/src/strconv/isprint.go" > src/isprint.ts
import { readFileSync } from 'node:fs';

const src = readFileSync(process.argv[2], 'utf8');
function table(name) {
  const m = src.match(new RegExp(`var ${name} = \\[\\]uint\\d+\\{([^}]*)\\}`));
  if (!m) throw new Error(`table ${name} not found`);
  return m[1].replace(/\/\/[^\n]*/g, '').split(',').map((s) => s.trim()).filter(Boolean).map((s) => parseInt(s, 16));
}
const out = [];
out.push('// Copyright 2013 The Go Authors. All rights reserved.');
out.push('// Use of this source code is governed by a BSD-style');
out.push('// license that can be found in the LICENSE-go file.');
out.push('');
out.push("// Derived from Go's strconv/isprint.go (generated by makeisprint.go).");
out.push('// Regenerate with scripts/gen-isprint.mjs.');
out.push('');
for (const [n, t] of [['isPrint16', 'isPrint16'], ['isNotPrint16', 'isNotPrint16'], ['isPrint32', 'isPrint32'], ['isNotPrint32', 'isNotPrint32']]) {
  const v = table(t);
  out.push(`export const ${n}: number[] = [`);
  for (let i = 0; i < v.length; i += 12) out.push('  ' + v.slice(i, i + 12).join(', ') + ',');
  out.push('];');
  out.push('');
}
process.stdout.write(out.join('\n'));
